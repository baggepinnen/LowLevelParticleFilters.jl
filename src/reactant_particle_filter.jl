"""
State of a [`ReactantParticleFilter`](@ref): the particles `x` and `xprev` are matrices (nx × N) on the device, the
weights and the resampling buffers are on the host, with the same field names as [`PFstate`](@ref).
"""
mutable struct DevicePFstate{XT, FT<:AbstractFloat}
    x::XT
    xprev::XT
    w::Vector{FT}
    we::Vector{FT}
    maxw::Base.RefValue{FT}
    j::Vector{Int64}
    bins::Vector{Float64}
    t::Base.RefValue{Int}
end

"""
    ReactantParticleFilter(pf::ParticleFilter; T = Float64, measurement_likelihood = nothing)
    ReactantParticleFilter(N, dynamics, measurement, dynamics_density, measurement_density, initial_density; T = Float64, measurement_likelihood = nothing, kwargs...)

A [`ParticleFilter`](@ref) whose particles are stored and propagated on an accelerator (GPU) with Reactant.jl.
Requires `using Reactant` (package extension).

The model is the one of `pf`: the same per-particle functions `dynamics(x, u, p, t)` and `measurement(x, u, p, t)`,
the additive Gaussian noise of `dynamics_density` and the density of the measurement noise `measurement_density`.
The functions are traced by Reactant for a single particle and evaluated for all particles at once on the device.
They must therefore be free of branches on the values of `x`, `u`, `p` and `t` (use `ifelse` instead of `if`) and of
calls to random-number generators. Optionally, `measurement_likelihood(x, u, y, p, t) -> log p(y | x)` replaces the
density of an additive measurement noise, for non-Gaussian measurement models.

Only the propagation of the particles ([`propagate_particles!`](@ref LowLevelParticleFilters.propagate_particles!)),
the log-likelihood of the measurements ([`measurement_equation!`](@ref LowLevelParticleFilters.measurement_equation!))
and the first-stage weights of an [`AuxiliaryParticleFilter`](@ref) are computed on the device. The weights, the
resampling and the remaining functionality of the package ([`update!`](@ref), [`loglik`](@ref),
[`forward_trajectory`](@ref), [`smooth`](@ref), `AuxiliaryParticleFilter(ReactantParticleFilter(pf))`, ...) operate on
the host as for the other particle filters. Each time step therefore transfers the weights (N numbers) from the
device to the host, and the ancestor indices (N integers) to the device after a resampling.

- `T`: precision of the particles on the device. `Float32` is faster on most GPUs but the accuracy may be
  insufficient for slow dynamics. The weights are computed on the host in `Float64`.
- `dynamics_density`: `nothing` (no noise) or a Gaussian density with `mean` and `cov` (`SimpleMvNormal`,
  `Distributions.MvNormal`).
- `measurement_density`: a Gaussian density as above, or `nothing` if `measurement_likelihood` is given.

The device noise is generated by a counter-based random-number generator with a key drawn from the random-number
generator `rng` of `pf` in every time step, so that the results are reproducible for a seeded `rng`. The functions
are compiled at the first call for each new combination of argument types and sizes, which may take several
seconds.
"""
struct ReactantParticleFilter{PF<:ParticleFilter, ST<:DevicePFstate, T, ML} <: AbstractParticleFilter
    "The filter that defines the model and the settings"
    pf::PF
    state::ST
    "Log-likelihood `(x, u, y, p, t) -> log p(y | x)` of a measurement, or `nothing` for `measurement_density`"
    measurement_likelihood::ML
    "Compiled device functions, by name and argument types"
    cache::Dict{Any, Any}
end


"""
    make_device_state(pf::ParticleFilter, T)

Device state of a [`ReactantParticleFilter`](@ref), defined in the Reactant extension
"""
function make_device_state end

function ReactantParticleFilter(pf::ParticleFilter; T::Type{<:AbstractFloat} = Float64, measurement_likelihood = nothing)
    isempty(methods(make_device_state)) &&
        error("ReactantParticleFilter requires Reactant.jl, load it with `using Reactant`")
    measurement_likelihood === nothing && pf.measurement_density === nothing &&
        throw(ArgumentError("either a measurement_density or a measurement_likelihood is required"))
    s = make_device_state(pf, T)
    ReactantParticleFilter{typeof(pf), typeof(s), T, typeof(measurement_likelihood)}(pf, s, measurement_likelihood, Dict{Any, Any}())
end

ReactantParticleFilter(N::Integer, args...; T::Type{<:AbstractFloat} = Float64, measurement_likelihood = nothing, kwargs...) =
    ReactantParticleFilter(ParticleFilter(N, args...; kwargs...); T, measurement_likelihood)

function Base.getproperty(pf::ReactantParticleFilter, s::Symbol)
    s ∈ fieldnames(ReactantParticleFilter) && return getfield(pf, s)
    s === :nx && return size(getfield(pf, :state).x, 1)
    getproperty(getfield(pf, :pf), s)
end

parameters(pf::ReactantParticleFilter) = parameters(pf.pf)

@forward ReactantParticleFilter.pf sample_state, sample_measurement, dynamics, measurement, dynamics_density, measurement_density, initial_density, resample_threshold, resampling_strategy, rng

"Precision of the particles on the device"
device_eltype(::ReactantParticleFilter{<:Any, <:Any, T}) where {T} = T

num_particles(s::DevicePFstate) = length(s.w)
weights(s::DevicePFstate) = s.w
# The device functions return new arrays and do not modify their arguments, so that the particles can be shared
store_previous!(s::DevicePFstate) = (s.xprev = s.x)
num_particles(pf::ReactantParticleFilter) = num_particles(state(pf))
weights(pf::ReactantParticleFilter) = weights(state(pf))
particletype(pf::ReactantParticleFilter) = SVector{pf.nx, device_eltype(pf)}

"""
    particles(pf::ReactantParticleFilter)

The particles copied from the device to the host, as a vector of `SVector`s.
"""
particles(pf::ReactantParticleFilter) = particles(state(pf))
particles(s::DevicePFstate) = collect(reinterpret(SVector{size(s.x, 1), eltype(s.x)}, vec(Array(s.x))))
weighted_mean(pf::ReactantParticleFilter) = weighted_mean(particles(pf), expweights(pf))

(pf::ReactantParticleFilter)(u, y, p = parameters(pf), t = index(pf)*pf.Ts) = update!(pf, u, y, p, t)
